
const form = document.getElementById("Learning-Form");
const result = document.getElementById("Result");
const roadmap = document.getElementById("Roadmap");

form.addEventListener("submit", async function(event) {

    event.preventDefault();

    const name = document.getElementById("name").value.trim();
    const goal = document.getElementById("goal").value;
    const level = document.getElementById("Level").value;

    try {

        // Send student details to Java
        const response = await fetch("/api/roadmap", {
            method: "POST",
            headers: {
                "Content-Type": "application/x-www-form-urlencoded"
            },
            body: new URLSearchParams({
                name: name,
                goal: goal,
                level: level
            })
        });

        if (!response.ok) {
            throw new Error("Unable to generate learning path.");
        }

        // Receive roadmap generated by Java
        const data = await response.json();

        roadmap.innerHTML = "";

        const heading = document.createElement("h3");
        heading.textContent = "Welcome, " + data.name + "!";
        roadmap.appendChild(heading);

        const description = document.createElement("p");
        description.textContent =
            "Learning Goal: " + data.goal +
            " | Skill Level: " + data.level;

        roadmap.appendChild(description);

        // Display learning topics
        data.topics.forEach(function(topic, index) {

            const card = document.createElement("div");
            card.className = "roadmap-item";

            const title = document.createElement("h3");
            title.textContent =
                "Step " + (index + 1) + ": " + topic.title;

            const details = document.createElement("p");
            details.textContent = topic.details;

            const checkbox = document.createElement("input");
            checkbox.type = "checkbox";

            const label = document.createElement("label");
            label.appendChild(checkbox);
            label.appendChild(
                document.createTextNode(" Mark as completed")
            );

            card.appendChild(title);
            card.appendChild(details);
            card.appendChild(label);

            roadmap.appendChild(card);
        });

        // Progress tracker
const progressContainer = document.createElement("div");
progressContainer.style.marginTop = "25px";
progressContainer.style.padding = "20px";
progressContainer.style.background = "#eee5ff";
progressContainer.style.borderRadius = "12px";

const progress = document.createElement("h3");
progress.style.color = "#7544c8";
progress.textContent = "Your Learning Progress: 0%";

const progressText = document.createElement("p");
progressText.textContent =
    "Completed: 0 / " + data.topics.length;

const progressBarBackground = document.createElement("div");
progressBarBackground.style.width = "100%";
progressBarBackground.style.height = "14px";
progressBarBackground.style.background = "#d8c8f5";
progressBarBackground.style.borderRadius = "20px";
progressBarBackground.style.marginTop = "12px";
progressBarBackground.style.overflow = "hidden";

const progressBar = document.createElement("div");
progressBar.style.width = "0%";
progressBar.style.height = "100%";
progressBar.style.background =
    "linear-gradient(90deg, #7544c8, #e36ca7)";
progressBar.style.borderRadius = "20px";
progressBar.style.transition = "width 0.4s ease";

progressBarBackground.appendChild(progressBar);

const completionMessage = document.createElement("p");
completionMessage.style.marginTop = "12px";
completionMessage.style.fontWeight = "bold";
completionMessage.style.color = "#7544c8";
completionMessage.textContent = "Keep going! You've got this!";

progressContainer.appendChild(progress);
progressContainer.appendChild(progressText);
progressContainer.appendChild(progressBarBackground);
progressContainer.appendChild(completionMessage);

roadmap.appendChild(progressContainer);

        const checkboxes = roadmap.querySelectorAll(
            'input[type="checkbox"]'
        );

        checkboxes.forEach(function(checkbox) {

    checkbox.addEventListener("change", function() {

        const completed = [...checkboxes]
            .filter(item => item.checked).length;

        const total = data.topics.length;

        const percentage = Math.round(
            (completed / total) * 100
        );

        progress.textContent =
            "Your Learning Progress: " + percentage + "%";

        progressText.textContent =
            "Completed: " + completed + " / " + total;

        progressBar.style.width = percentage + "%";

        if (percentage === 100) {
            completionMessage.textContent =
                "Congratulations! You've completed your learning path! 🎉";
        } else {
            completionMessage.textContent =
                "Keep going! You've got this!";
        }
    });
});

        result.hidden = false;
        result.scrollIntoView({ behavior: "smooth" });

    } catch (error) {

        alert("Error: " + error.message);
        console.error(error);

    }
});
